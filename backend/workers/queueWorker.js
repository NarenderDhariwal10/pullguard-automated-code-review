const { Worker } = require('bullmq');

const { generateReview } =
    require('../services/aiService');

const { commentOnPR } =
    require('../services/githubService');

const Review =
    require('../models/reviewModel');

const { redisOptions } =
    require('../utils/helpers');



// Generate GitHub comment


function formatReviewForGitHub(review) {

    let comment = '';

    comment += `## Summary\n`;
    comment += `${review.summary}\n\n`;


    // Group issues by severity

    const severities = [
        'HIGH',
        'MEDIUM',
        'LOW'
    ];


    for (const severity of severities) {

        const issues =
            review.issues.filter(
                issue => issue.severity === severity
            );

        if (issues.length === 0) {
            continue;
        }


        comment += `### [${severity}]\n`;

        for (const issue of issues) {

            comment +=
                `- **${issue.title}**: ` +
                `${issue.suggestedFix}\n`;
        }

        comment += `\n`;
    }


    comment += `### Overall Score\n`;
    comment += `${review.overallScore}/100\n\n`;

    comment += `### Recommendation\n`;
    comment += `${review.recommendation}\n\n`;

    comment += `---\n`;
    comment += `*Generated by PullGuard AI*`;


    return comment;
}



// Calculate issue counts

function calculateIssueCounts(issues) {

    const counts = {
        high: 0,
        medium: 0,
        low: 0
    };


    for (const issue of issues) {

        const severity =
            String(issue.severity || '')
                .toUpperCase();

        if (severity === 'HIGH') {
            counts.high++;
        }

        else if (severity === 'MEDIUM') {
            counts.medium++;
        }

        else if (severity === 'LOW') {
            counts.low++;
        }
    }


    return counts;
}



// Worker


new Worker(
    'reviewQueue',

    async job => {

        console.log('review started', job.id);


        try {

            
            // AI Works
            
            const aiReview =
                await generateReview(
                    job.data.code || '',
                    job.data.filename ||
                    `PR #${job.data.pull_number}`
                );


      
            // Issue counts

            const issueCounts =
                calculateIssueCounts(
                    aiReview.issues || []
                );



            // GitHub comment
            
            const githubComment =
                formatReviewForGitHub(
                    aiReview
                );


            await commentOnPR(
                {
                    owner: job.data.owner,
                    repo: job.data.repo,
                    pull_number:
                        job.data.pull_number
                },
                githubComment
            );



            // MongoDB document save            

            const reviewDoc =
                new Review({

                    prNumber:
                        job.data.pull_number,

                    prTitle:
                        job.data.title ||
                        `Pull Request #${job.data.pull_number}`,

                    prUrl:
                        job.data.prUrl || '',

                    repo:
                        job.data.repo,

                    owner:
                        job.data.owner,

                    filename:
                        job.data.filename || null,

                    filesReviewed:
                        job.data.filesReviewed || [],

                    status:
                        'completed',

                    summary:
                        aiReview.summary,

                    overallScore:
                        aiReview.overallScore,

                    recommendation:
                        aiReview.recommendation
                            .toLowerCase(),

                    issues:
                        aiReview.issues || [],

                    categoryScores: {

                        security:
                            aiReview.categoryScores
                                ?.security ?? 0,

                        performance:
                            aiReview.categoryScores
                                ?.performance ?? 0,

                        maintainability:
                            aiReview.categoryScores
                                ?.maintainability ?? 0,

                        bestPractices:
                            aiReview.categoryScores
                                ?.bestPractices ?? 0
                    },

                    issueCounts,

                    comment:
                        githubComment,

                    isDemo:
                        false
                });


            await reviewDoc.save();


            return {
                success: true,
                reviewId:
                    reviewDoc._id.toString()
            };

        } catch (err) {

            console.error(
                'Review job failed:',
                err.response?.data ||
                err.message
            );

            throw err;
        }
    },

    {
        connection: redisOptions
    }
);